#!/usr/bin/env bun
// Copies the repository's draft schemas into src/schemas.ts so the package ships exactly the
// bytes it was built from, pinned by commit and digest (spec §4.5: a draft's version string does
// not identify exact bytes). A reader resolves a line's `(id, version)` pair against these and no
// others (§4.6). Run from the package directory. A test fails when the copy is stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";

const root = resolve(import.meta.dir, "../../..");
const dir = join(root, "schemas");
const files = readdirSync(dir).filter((f) => f.endsWith(".schema.json")).sort();
const commit = spawnSync("git", ["-C", root, "rev-parse", "HEAD"], { encoding: "utf8" }).stdout.trim();
const entries = files.map((f) => {
  const bytes = readFileSync(join(dir, f));
  const schema = JSON.parse(bytes.toString("utf8")) as { properties: { _schema: { properties: { id: { const: string }; version: { const: string } } } } };
  return { file: f, id: schema.properties._schema.properties.id.const, version: schema.properties._schema.properties.version.const, sha256: createHash("sha256").update(bytes).digest("hex"), schema };
});
const out = [
  "// Generated by scripts/sync-schemas.ts. Do not edit; edit schemas/ at the repository root.",
  `export const SCHEMA_SOURCE = { commit: ${JSON.stringify(commit)}, files: ${JSON.stringify(Object.fromEntries(entries.map((e) => [e.file, e.sha256])), null, 2)} } as const;`,
  `export const SCHEMAS: ReadonlyArray<{ id: string; version: string; schema: Record<string, unknown> }> = ${JSON.stringify(entries.map(({ id, version, schema }) => ({ id, version, schema })), null, 2)};`,
  "",
].join("\n");
writeFileSync(join(import.meta.dir, "../src/schemas.ts"), out);
console.log(JSON.stringify({ event: "sync-schemas", commit, files: files.length }));
